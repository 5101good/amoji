import { build } from "esbuild";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
// Mods statically follows `$` only inside one file. Bundle this host adapter,
// keeping domain/application/Node modules outside its restricted environment.
await build({
  entryPoints: [resolve(root, "src/claude-mods/native/register.js")],
  outfile: resolve(root, "plugins/amoji-claude-mods/hooks/register.js"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2023",
  banner: {
    js: "// Generated by scripts/build-claude-mods-ui.mjs. Edit src/claude-mods/native/.",
  },
});
